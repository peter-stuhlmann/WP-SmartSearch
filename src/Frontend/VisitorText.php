<?php
/**
 * The texts visitors read, in the address the website uses.
 *
 * @package PrstSearch
 */

declare( strict_types=1 );

namespace PrstSearch\Frontend;

use PrstSearch\Settings\Settings;

/**
 * Speaks to visitors the way the website does.
 *
 * Some websites address their visitors informally, others formally – in
 * German "du" or "Sie". Every text that speaks to a visitor exists in both
 * forms; the formal one is the same English text with the context "formal
 * address", so a translation can tell them apart. Which one is used, the
 * setting decides, and by default the language of the website: "Deutsch (Sie)"
 * speaks formally.
 *
 * Texts the website owner writes, such as the message for too many searches,
 * can be translated with Polylang or WPML like any other string of the site.
 */
final class VisitorText {

	/**
	 * Group of the owner's own texts in the string translation of Polylang and WPML.
	 */
	private const STRING_GROUP = 'Smart Search';

	/**
	 * Creates the service.
	 */
	public function __construct( private readonly Settings $settings ) {}

	/**
	 * Tells whether visitors are addressed formally.
	 */
	public function is_formal(): bool {
		return match ( $this->settings->string( 'visitor_address' ) ) {
			'formal'   => true,
			'informal' => false,
			default    => str_ends_with( get_locale(), '_formal' ),
		};
	}

	/**
	 * Returns a text in the address the website uses.
	 *
	 * @param string $key One of "error", "more_error", "too_many", "answer_note", "corrected", "no_results",
	 *                    "privacy_log", "privacy_ai".
	 */
	public function get( string $key ): string {
		$formal = $this->is_formal();

		return match ( $key ) {
			'error'       => $formal
				? _x( 'The search is not available at the moment. Please try again.', 'formal address', 'smart-search' )
				: __( 'The search is not available at the moment. Please try again.', 'smart-search' ),
			'more_error'  => $formal
				? _x( 'More results could not be loaded. Please try again.', 'formal address', 'smart-search' )
				: __( 'More results could not be loaded. Please try again.', 'smart-search' ),
			'too_many'    => $formal
				? _x( 'You have searched very often in a short time. Please wait a moment and try again.', 'formal address', 'smart-search' )
				: __( 'You have searched very often in a short time. Please wait a moment and try again.', 'smart-search' ),
			'answer_note' => $formal
				? _x( 'This answer was generated by AI from the content of this website. Please check important details against the sources.', 'formal address', 'smart-search' )
				: __( 'This answer was generated by AI from the content of this website. Please check important details against the sources.', 'smart-search' ),
			'corrected'   => $formal
				/* translators: %s: corrected search phrase. */
				? _x( 'Nothing was found for your spelling. Showing results for “%s”.', 'formal address', 'smart-search' )
				/* translators: %s: corrected search phrase. */
				: __( 'Nothing was found for your spelling. Showing results for “%s”.', 'smart-search' ),
			'no_results'  => $formal
				? _x( 'Try fewer or more general words, or check the spelling.', 'formal address', 'smart-search' )
				: __( 'Try fewer or more general words, or check the spelling.', 'smart-search' ),
			'privacy_log' => $formal
				? _x( 'When you use the search on this website, we store the search phrase, the time, the number of results and, where applicable, which result was opened. We use this to improve the search and our content. We do not store your IP address or any other data that identifies you.', 'formal address', 'smart-search' )
				: __( 'When you use the search on this website, we store the search phrase, the time, the number of results and, where applicable, which result was opened. We use this to improve the search and our content. We do not store your IP address or any other data that identifies you.', 'smart-search' ),
			'privacy_ai'  => $formal
				? _x( 'If semantic search or AI answers are enabled, your search phrase and excerpts of our public content are transmitted to the AI provider we use, in order to find matching content and to write an answer.', 'formal address', 'smart-search' )
				: __( 'If semantic search or AI answers are enabled, your search phrase and excerpts of our public content are transmitted to the AI provider we use, in order to find matching content and to write an answer.', 'smart-search' ),
			default       => '',
		};
	}

	/**
	 * Returns a text the website owner wrote in a setting, translated if a multilingual plugin knows it.
	 *
	 * @param string $setting  Name of the setting.
	 * @param string $fallback What is used if the setting is empty.
	 */
	public function own( string $setting, string $fallback ): string {
		$text = trim( $this->settings->string( $setting ) );

		if ( '' === $text ) {
			return $fallback;
		}

		if ( function_exists( 'pll__' ) ) {
			return (string) pll__( $text );
		}

		// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- The hook of WPML.
		return (string) apply_filters( 'wpml_translate_single_string', $text, self::STRING_GROUP, $setting );
	}

	/**
	 * Tells Polylang and WPML about a text the owner wrote, so it can be translated there.
	 *
	 * @param string $setting Name of the setting.
	 * @param string $label   Name shown in the string translation.
	 */
	public function register_own( string $setting, string $label ): void {
		$text = trim( $this->settings->string( $setting ) );

		if ( '' === $text ) {
			return;
		}

		if ( function_exists( 'pll_register_string' ) ) {
			pll_register_string( $label, $text, self::STRING_GROUP, true );
		}

		// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- The hook of WPML.
		do_action( 'wpml_register_single_string', self::STRING_GROUP, $setting, $text );
	}
}
