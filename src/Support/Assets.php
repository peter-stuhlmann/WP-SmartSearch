<?php
/**
 * Registers built assets.
 *
 * @package PrstSearch
 */

declare( strict_types=1 );

namespace PrstSearch\Support;

/**
 * Knows where the build output lives and how to register it.
 */
final class Assets {

	/**
	 * Creates the helper.
	 *
	 * @param string $build_dir Absolute path of the build directory, with trailing slash.
	 * @param string $build_url URL of the build directory, with trailing slash.
	 * @param string $languages Absolute path of the languages directory.
	 */
	public function __construct(
		private readonly string $build_dir,
		private readonly string $build_url,
		private readonly string $languages
	) {}

	/**
	 * Registers a script with the dependencies and version generated by the build.
	 *
	 * @param string   $handle Script handle.
	 * @param string   $name   File name in the build directory, without extension.
	 * @param string[] $extra  Additional dependencies.
	 */
	public function register_script( string $handle, string $name, array $extra = array() ): void {
		$meta = $this->meta( $name );

		wp_register_script(
			$handle,
			$this->build_url . $name . '.js',
			array_merge( $meta['dependencies'], $extra ),
			$meta['version'],
			array( 'in_footer' => true )
		);

		wp_set_script_translations( $handle, 'smart-search', $this->languages );
	}

	/**
	 * Registers a stylesheet.
	 *
	 * @param string   $handle       Style handle.
	 * @param string   $name         File name in the build directory, without extension.
	 * @param string[] $dependencies Style dependencies.
	 */
	public function register_style( string $handle, string $name, array $dependencies = array() ): void {
		wp_register_style( $handle, $this->build_url . $name . '.css', $dependencies, $this->meta( $name )['version'] );

		// The build writes a mirrored copy of every stylesheet. This tells WordPress to load it for right-to-left languages.
		wp_style_add_data( $handle, 'rtl', 'replace' );
	}

	/**
	 * Reads the asset file written by the build.
	 *
	 * @return array{dependencies: string[], version: string}
	 */
	private function meta( string $name ): array {
		$file = $this->build_dir . $name . '.asset.php';
		$meta = is_readable( $file ) ? require $file : array();

		return array(
			'dependencies' => (array) ( $meta['dependencies'] ?? array() ),
			'version'      => (string) ( $meta['version'] ?? PRSTSEARCH_VERSION ),
		);
	}
}
